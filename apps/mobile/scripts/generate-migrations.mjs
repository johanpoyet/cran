// `pnpm db:generate [--name x]`: runs drizzle-kit generate, then embeds the SQL migrations of
// drizzle/ in src/db/migrations.ts, in the shape expected by Drizzle's expo-sqlite migrator (Metro
// cannot import .sql files without extra configuration).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

execFileSync('drizzle-kit', ['generate', ...process.argv.slice(2)], { stdio: 'inherit' });

const folder = new URL('../drizzle/', import.meta.url);
const journal = JSON.parse(readFileSync(new URL('meta/_journal.json', folder), 'utf8'));
const migrations = Object.fromEntries(
  journal.entries.map((entry) => [
    `m${String(entry.idx).padStart(4, '0')}`,
    readFileSync(new URL(`${entry.tag}.sql`, folder), 'utf8'),
  ]),
);

const output = fileURLToPath(new URL('../src/db/migrations.ts', import.meta.url));
writeFileSync(
  output,
  `// Generated by scripts/generate-migrations.mjs from drizzle/ (pnpm db:generate). Do not edit.

export default {
  journal: ${JSON.stringify(journal)},
  migrations: ${JSON.stringify(migrations)},
};
`,
);
execFileSync('prettier', ['--write', output], { stdio: 'inherit' });
