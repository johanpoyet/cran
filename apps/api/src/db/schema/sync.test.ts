import { eq, sql } from 'drizzle-orm';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { buildTestApp } from '../../test/app';
import { createTestDatabase, type TestDatabase } from '../../test/database';
import { signUpUser } from '../../test/session';
import {
  favorites,
  foods,
  logEntries,
  mealTemplateItems,
  mealTemplates,
  measurements,
  recipeIngredients,
  recipes,
  user,
  waterLogs,
} from './index';

let database: TestDatabase;
let app: ReturnType<typeof buildTestApp>['app'];

beforeAll(async () => {
  database = await createTestDatabase();
  app = buildTestApp({ db: database.db }).app;
});

afterAll(async () => {
  await database.close();
});

/** Rows of a raw query, whatever the driver (postgres.js returns an array, PGlite an object). */
async function rows<T>(query: ReturnType<typeof sql>): Promise<T[]> {
  const result: unknown = await database.db.execute(query);
  return (Array.isArray(result) ? result : (result as { rows: T[] }).rows) as T[];
}

const entry = (userId: string) => ({
  userId,
  date: '2026-11-03',
  mealType: 'lunch' as const,
  label: 'Riz basmati cuit',
  grams: 250,
  kcal: 325,
  proteinG: 6.75,
  carbsG: 70,
  fatG: 1,
  loggedAt: new Date(),
});

describe('server_seq', () => {
  it('has a trigger on every table with a server_seq column', async () => {
    const tables = await rows<{ table_name: string }>(
      sql`select table_name from information_schema.columns
          where column_name = 'server_seq' and table_schema = 'public' order by table_name`,
    );
    const triggers = await rows<{ table_name: string }>(
      sql`select c.relname as table_name from pg_trigger t join pg_class c on c.oid = t.tgrelid
          where t.tgname = c.relname || '_server_seq' and not t.tgisinternal order by c.relname`,
    );

    expect(tables.map(({ table_name }) => table_name)).toEqual([
      'favorites',
      'food_portions',
      'foods',
      'log_entries',
      'meal_template_items',
      'meal_templates',
      'measurements',
      'profiles',
      'recipe_ingredients',
      'recipes',
      'water_logs',
      'weekly_targets',
      'weigh_ins',
    ]);
    expect(triggers.map(({ table_name }) => table_name)).toEqual(
      tables.map(({ table_name }) => table_name),
    );
  });

  it('moves forward on every update, across tables, without the code setting it', async () => {
    const owner = await signUpUser(app);
    const [first] = await database.db.insert(logEntries).values(entry(owner.id)).returning();
    const [water] = await database.db
      .insert(waterLogs)
      .values({ userId: owner.id, date: '2026-11-03', ml: 250 })
      .returning();
    expect(water?.serverSeq).toBeGreaterThan(first?.serverSeq ?? 0);

    const [updated] = await database.db
      .update(logEntries)
      .set({ grams: 100, updatedAt: new Date() })
      .where(eq(logEntries.id, first?.id ?? ''))
      .returning();

    // The latest write of any table comes last in the cursor order.
    expect(updated?.serverSeq).toBeGreaterThan(water?.serverSeq ?? 0);
  });

  it('cannot be set back by a client value', async () => {
    const owner = await signUpUser(app);
    const [row] = await database.db
      .insert(waterLogs)
      .values({ userId: owner.id, date: '2026-11-03', ml: 250 })
      .returning();

    const [updated] = await database.db
      .update(waterLogs)
      .set({ serverSeq: 1 })
      .where(eq(waterLogs.id, row?.id ?? ''))
      .returning();

    expect(updated?.serverSeq).toBeGreaterThan(row?.serverSeq ?? 0);
  });
});

describe('journal tables', () => {
  it('keep the id generated by the client', async () => {
    const owner = await signUpUser(app);
    const id = '019a4b2c-1d2e-7f30-8a41-b5c6d7e8f901';

    const [row] = await database.db
      .insert(logEntries)
      .values({ ...entry(owner.id), id })
      .returning();

    expect(row?.id).toBe(id);
  });

  it('accept a quick add without quantity and refuse negative values', async () => {
    const owner = await signUpUser(app);
    await expect(
      database.db
        .insert(logEntries)
        .values({ ...entry(owner.id), grams: null, label: 'Ajout rapide' }),
    ).resolves.toBeDefined();
    await expect(
      database.db.insert(logEntries).values({ ...entry(owner.id), kcal: -1 }),
    ).rejects.toThrow();
    await expect(
      database.db.insert(waterLogs).values({ userId: owner.id, date: '2026-11-03', ml: 0 }),
    ).rejects.toThrow();
  });

  it('keep an entry when its food is deleted', async () => {
    const owner = await signUpUser(app);
    const [food] = await database.db
      .insert(foods)
      .values({
        source: 'user',
        ownerId: owner.id,
        name: 'Galette',
        kcal100g: 162,
        protein100g: 6,
        carbs100g: 30,
        fat100g: 2,
      })
      .returning();
    const [row] = await database.db
      .insert(logEntries)
      .values({ ...entry(owner.id), foodId: food?.id ?? null })
      .returning();

    await database.db.delete(foods).where(eq(foods.id, food?.id ?? ''));

    const [after] = await database.db
      .select()
      .from(logEntries)
      .where(eq(logEntries.id, row?.id ?? ''));
    expect(after).toMatchObject({ foodId: null, kcal: 325 });
  });
});

describe('recipes and templates', () => {
  async function recipeWithIngredient(userId: string) {
    const [food] = await database.db
      .insert(foods)
      .values({
        source: 'user',
        ownerId: userId,
        name: 'Riz',
        kcal100g: 130,
        protein100g: 2.7,
        carbs100g: 28,
        fat100g: 0.4,
      })
      .returning();
    const [recipe] = await database.db
      .insert(recipes)
      .values({ userId, name: 'Riz au lait', servings: 4, cookedWeightG: 1200 })
      .returning();
    const foodId = food?.id ?? '';
    const recipeId = recipe?.id ?? '';
    await database.db
      .insert(recipeIngredients)
      .values({ userId, recipeId, foodId, grams: 200, position: 0 });
    return { foodId, recipeId };
  }

  it('delete the ingredients and favourites of a deleted recipe', async () => {
    const owner = await signUpUser(app);
    const { recipeId } = await recipeWithIngredient(owner.id);
    await database.db.insert(favorites).values({ userId: owner.id, recipeId });

    await database.db.delete(recipes).where(eq(recipes.id, recipeId));

    expect(
      await database.db
        .select()
        .from(recipeIngredients)
        .where(eq(recipeIngredients.recipeId, recipeId)),
    ).toEqual([]);
    expect(
      await database.db.select().from(favorites).where(eq(favorites.recipeId, recipeId)),
    ).toEqual([]);
  });

  it('keep a recipe used by a meal template, whose items hold a food or a recipe', async () => {
    const owner = await signUpUser(app);
    const { foodId, recipeId } = await recipeWithIngredient(owner.id);
    const [template] = await database.db
      .insert(mealTemplates)
      .values({ userId: owner.id, name: 'Shaker', mealType: 'snack' })
      .returning();
    const templateId = template?.id ?? '';
    await database.db
      .insert(mealTemplateItems)
      .values({ userId: owner.id, templateId, recipeId, grams: 300, position: 0 });

    await expect(
      database.db
        .insert(mealTemplateItems)
        .values({ userId: owner.id, templateId, foodId, recipeId, grams: 1, position: 1 }),
    ).rejects.toThrow();
    await expect(database.db.delete(recipes).where(eq(recipes.id, recipeId))).rejects.toThrow();
  });
});

describe('account deletion', () => {
  it('removes every synchronised row of the user', async () => {
    const owner = await signUpUser(app);
    await database.db.insert(logEntries).values(entry(owner.id));
    await database.db.insert(waterLogs).values({ userId: owner.id, date: '2026-11-03', ml: 250 });
    await database.db
      .insert(measurements)
      .values({ userId: owner.id, date: '2026-11-03', waistCm: 78.5 });
    await database.db
      .insert(recipes)
      .values({ userId: owner.id, name: 'Riz au lait', servings: 4 });

    await database.db.delete(user).where(eq(user.id, owner.id));

    for (const table of [logEntries, waterLogs, measurements, recipes]) {
      expect(await database.db.select().from(table).where(eq(table.userId, owner.id))).toEqual([]);
    }
  });
});
